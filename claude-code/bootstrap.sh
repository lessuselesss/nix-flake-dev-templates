#!/usr/bin/env bash
#
# bootstrap.sh — get a working Nix into an environment that has none.
#
# This solves the chicken-and-egg problem you hit inside a fresh sandbox
# (Claude Code on the web, a bare CI runner, a container, ...): you want to
# `nix develop` one of the templates in this repo, but `nix` isn't installed
# and there is no root/NixOS to lean on.
#
# Strategy (first one that works wins):
#   1. Already have a usable `nix`?            -> do nothing.
#   2. nix-portable (rootless, single binary)  -> preferred; needs GitHub.
#   3. Official static tarball from            -> fallback; needs
#      releases.nixos.org                          write access to /nix.
#
# Only cache.nixos.org / releases.nixos.org are required at runtime. In the
# Claude Code web sandbox, GitHub is proxy-gated to the session's own repo,
# so step 2 fails there and step 3 is what actually succeeds — that's fine,
# the script falls through automatically.
#
# Usage:
#   ./claude-code/bootstrap.sh          # install + write an activation file
#   . ./.nix-bootstrap-env.sh           # activate in the current shell
#   nix --version                       # verify
#
# Idempotent: safe to re-run. Override defaults with env vars:
#   NIX_VERSION      (default 2.30.1)   static-tarball version to fetch
#   NP_PREFIX        (default $HOME/.local/share/nix-portable)
#   ENV_FILE         (default $PWD/.nix-bootstrap-env.sh)

set -euo pipefail

NIX_VERSION="${NIX_VERSION:-2.30.1}"
NP_PREFIX="${NP_PREFIX:-$HOME/.local/share/nix-portable}"
ENV_FILE="${ENV_FILE:-$PWD/.nix-bootstrap-env.sh}"
CACHE="https://cache.nixos.org"

# Activation snippet for a single-user (static-tarball) install. The stock
# nix.sh no-ops unless USER is set, so set it first and prepend the profile
# bin directly — this makes activation work even in bare `env -i` shells.
SINGLE_USER_SNIPPET='export USER="${USER:-$(id -un)}"
export PATH="$HOME/.nix-profile/bin:$PATH"
[ -e "$HOME/.nix-profile/etc/profile.d/nix.sh" ] && . "$HOME/.nix-profile/etc/profile.d/nix.sh"'

log()  { printf '\033[1;34m[bootstrap]\033[0m %s\n' "$*" >&2; }
warn() { printf '\033[1;33m[bootstrap]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[bootstrap]\033[0m %s\n' "$*" >&2; exit 1; }

arch() {
  case "$(uname -m)" in
    x86_64|amd64)  echo x86_64 ;;
    aarch64|arm64) echo aarch64 ;;
    *) die "unsupported CPU architecture: $(uname -m)" ;;
  esac
}

# Emit a sourceable activation file and tell the user how to use it.
write_env_file() {
  # $1 = shell snippet that puts `nix` on PATH for this install method
  cat > "$ENV_FILE" <<EOF
# Auto-generated by claude-code/bootstrap.sh — source me to use Nix:
#   . $ENV_FILE
$1
export NIX_CONFIG="experimental-features = nix-command flakes
build-users-group =
sandbox = false"
EOF
  log "wrote activation file: $ENV_FILE"
  log "activate with:  . $ENV_FILE"
}

# Write a Nix config enabling flakes + rootless builds, wherever we can.
write_nix_conf() {
  local conf
  if [ -w /etc/nix ] || { [ "$(id -u)" = 0 ] && mkdir -p /etc/nix 2>/dev/null; }; then
    conf=/etc/nix/nix.conf
  else
    mkdir -p "$HOME/.config/nix"
    conf="$HOME/.config/nix/nix.conf"
  fi
  cat > "$conf" <<EOF
experimental-features = nix-command flakes
build-users-group =
sandbox = false
substituters = $CACHE
EOF
  log "wrote Nix config: $conf"
}

# ---------------------------------------------------------------------------
# 1. Already installed?
# ---------------------------------------------------------------------------
if command -v nix >/dev/null 2>&1; then
  log "nix already on PATH: $(nix --version 2>/dev/null || true) — nothing to do."
  exit 0
fi
# A previous run of this script may have installed Nix without leaving it on
# PATH in a fresh shell. Detect that and just re-export it.
if [ -x "$HOME/.nix-profile/bin/nix" ]; then
  log "found existing single-user Nix at ~/.nix-profile — re-activating."
  write_env_file "$SINGLE_USER_SNIPPET"
  exit 0
fi
if [ -x "$NP_PREFIX/bin/nix" ]; then
  log "found existing nix-portable at $NP_PREFIX — re-activating."
  write_env_file "export PATH=\"$NP_PREFIX/bin:\$PATH\""
  exit 0
fi

# ---------------------------------------------------------------------------
# 2. Try nix-portable (rootless, no /nix required). Needs GitHub reachable.
# ---------------------------------------------------------------------------
try_nix_portable() {
  local a url bin
  a="$(arch)"
  url="https://github.com/DavHau/nix-portable/releases/latest/download/nix-portable-${a}"
  bin="$NP_PREFIX/nix-portable"

  log "attempting nix-portable ($a) from GitHub ..."
  mkdir -p "$NP_PREFIX/bin"
  if ! curl -fsSL --connect-timeout 20 -o "$bin" "$url"; then
    warn "could not download nix-portable (GitHub may be blocked here)."
    return 1
  fi
  # A proxy denial can return a tiny JSON/HTML body with a 200; sanity-check.
  if [ "$(stat -c%s "$bin" 2>/dev/null || echo 0)" -lt 1000000 ]; then
    warn "downloaded nix-portable looks wrong ($(stat -c%s "$bin" 2>/dev/null) bytes) — skipping."
    rm -f "$bin"; return 1
  fi
  chmod +x "$bin"
  # nix-portable dispatches on argv[0]; symlink the common entry points.
  local p
  for p in nix nix-shell nix-env nix-build nix-store nix-collect-garbage; do
    ln -sf "$bin" "$NP_PREFIX/bin/$p"
  done
  if ! "$NP_PREFIX/bin/nix" --version >/dev/null 2>&1; then
    warn "nix-portable downloaded but failed to run — falling back."
    return 1
  fi
  log "nix-portable works: $("$NP_PREFIX/bin/nix" --version 2>/dev/null)"
  write_env_file "export PATH=\"$NP_PREFIX/bin:\$PATH\""
  return 0
}

# ---------------------------------------------------------------------------
# 3. Fallback: official static tarball from releases.nixos.org into /nix.
# ---------------------------------------------------------------------------
try_static_tarball() {
  local a url tmp pkg
  a="$(arch)"
  url="https://releases.nixos.org/nix/nix-${NIX_VERSION}/nix-${NIX_VERSION}-${a}-linux.tar.xz"

  # /nix must be creatable/writable. As root we make it; otherwise we need it
  # to already exist and be writable (single-user installs usually chown it).
  if [ ! -w /nix ] && [ ! -e /nix ]; then
    if [ "$(id -u)" = 0 ]; then
      mkdir -m 0755 /nix && chown "$(id -u)" /nix
    elif command -v sudo >/dev/null 2>&1; then
      sudo mkdir -m 0755 /nix && sudo chown "$(id -u)" /nix
    else
      die "cannot create /nix (not root, no sudo). Use nix-portable on a machine with GitHub access instead."
    fi
  fi

  log "downloading static Nix $NIX_VERSION ($a) from releases.nixos.org ..."
  tmp="$(mktemp -d)"
  curl -fsSL --connect-timeout 30 -o "$tmp/nix.tar.xz" "$url" \
    || die "download failed: $url"
  tar -xJf "$tmp/nix.tar.xz" -C "$tmp"
  local unpacked="$tmp/nix-${NIX_VERSION}-${a}-linux"
  [ -d "$unpacked" ] || die "unexpected tarball layout under $tmp"

  # The bundled installer copies the store correctly but its final step fails
  # in a rootless/no-nixbld environment. Run it, tolerate that failure, then
  # finish the profile ourselves — the same repair proven to work by hand.
  log "installing (the 'nixbld group' warning at the end is expected) ..."
  ( cd "$unpacked" && yes | ./install --no-daemon --no-channel-add ) >&2 || true

  write_nix_conf

  pkg="$(ls -d /nix/store/*-nix-${NIX_VERSION} 2>/dev/null | head -1)"
  [ -n "$pkg" ] || die "Nix store package not found after install — cannot continue."
  log "activating profile from $pkg ..."
  "$pkg/bin/nix-env" -i "$pkg" >&2

  [ -x "$HOME/.nix-profile/bin/nix" ] || die "profile activation did not yield a nix binary."
  log "static Nix works: $("$HOME/.nix-profile/bin/nix" --version 2>/dev/null)"
  write_env_file "$SINGLE_USER_SNIPPET"
  rm -rf "$tmp"
  return 0
}

command -v curl >/dev/null 2>&1 || die "curl is required but not installed."

if try_nix_portable; then
  :
elif try_static_tarball; then
  :
else
  die "all bootstrap methods failed."
fi

log "done. Next:"
log "  . $ENV_FILE          # put nix on PATH in this shell"
log "  nix --version        # verify"
log "  nix develop          # enter a template's dev shell"
